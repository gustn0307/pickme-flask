
"""결정 도우미의 비즈니스 로직 담당."""
# 이 파일은 AI 상담에 필요한 설정을 관리하고,
# 사용자의 고민을 AI에게 전달할 질문으로 만드는 역할을 한다.

import os  # 운영체제 환경변수를 읽기 위한 모듈
from google import genai  # Gemini AI를 사용하기 위한 라이브러리
from google.genai import types  # Gemini 요청 설정을 지정하기 위한 모듈


# 개선 1: 고민 카테고리 (복수 선택 가능)
# 사용자가 고민의 종류를 선택할 수 있도록 카테고리를 정의한다.
# 여러 카테고리를 동시에 선택할 수 있다.
CATEGORIES = [
    "음식/식사", "진로/직업", "소비/쇼핑", "연애/관계",
    "일상/생활", "학습/자기계발", "여행/여가", "기타",
]

# 개선 2: AI 조언 스타일 (상담 중 변경 가능)
# 딕셔너리의 key는 프로그램에서 사용하는 스타일 식별값이다.
# value는 AI가 해당 스타일로 답변하도록 전달하는 설명이다.
STYLES = {
    "soft": "따뜻한 공감형: 친구 같은 어조로 먼저 충분히 공감해주고, 장점 중심으로 부드럽게 조언한다.",
    "objective": "객관적인 분석형: 근거 기반 논리와 데이터처럼 객관적인 시각으로 균형 잡힌 조언을 한다.",
    "fact": "냉정한 팩트형: 우유부단함 없이 현실적이고 냉정하게, 핵심만 간결하게 짚어준다.",
}

# 개선 5: 자주 쓰는 추가 조건 칩 (체크박스)
# 사용자가 매번 직접 입력하지 않아도 자주 사용하는 조건을 선택할 수 있다.
# 선택한 조건은 고민 내용과 함께 AI에게 전달된다.
CONDITION_CHIPS = [
    "예산이 정해져 있음",
    "시간이 급함",
    "식사/일정 후 바로 약속이 있음",
    "주변 사람 의견이 중요",
    "건강/체질을 고려해야 함",
]


# 응답 속도 개선: 가벼운 모델부터 순서대로 시도 (실패 시 다음 모델로 자동 전환)
# AI 모델 이름을 리스트에 저장한다.
# 앞에 있는 모델의 요청이 실패하면 다음 모델을 시도한다.
MODELS = [
    "gemini-flash-lite-latest",
    "gemini-flash-latest",
    "gemini-2.0-flash",
]


def get_ai_consultation(prompt: str) -> str:
    """Gemini 모델을 사용하여 AI 상담/결정 도우미 응답을 생성합니다."""

    # 환경변수에서 Gemini API 키를 가져온다.
    # API 키를 코드에 직접 작성하지 않아도 된다.
    api_key = os.environ.get("GEMINI_API_KEY")

    # API 키가 설정되지 않았다면 오류 안내를 문자열로 반환한다.
    # return을 실행하면 이 함수는 여기서 종료된다.
    if not api_key:
        return "오류: GEMINI_API_KEY가 설정되지 않았습니다. .env 파일을 확인해주세요."

    # API 키를 사용해 Gemini 클라이언트 객체를 생성한다.
    # 클라이언트는 AI 모델에 요청을 보내는 역할을 한다.
    client = genai.Client(api_key=api_key)

    # 모델 요청이 실패했을 때 마지막 오류를 저장할 변수
    last_error = None

    # MODELS 리스트에 있는 모델을 하나씩 순서대로 확인한다.
    for model in MODELS:
        try:
            # 선택한 모델에 프롬프트를 전달하고 AI 응답을 요청한다.
            response = client.models.generate_content(
                model=model,  # 현재 사용할 AI 모델 이름
                contents=prompt,  # AI에게 전달할 상담 질문
                config=types.GenerateContentConfig(
                    temperature=0.7,  # 답변의 다양성과 창의성에 영향을 주는 설정
                    max_output_tokens=800,  # 생성할 응답의 최대 토큰 수
                )
            )

            # AI가 생성한 응답 텍스트를 반환한다.
            # return이 실행되면 함수가 종료되므로 다음 모델은 실행하지 않는다.
            return response.text

        except Exception as e:
            # 현재 모델에서 오류가 발생하면 오류 내용을 저장한다.
            last_error = e

            # 현재 모델의 실패를 처리하고 다음 모델로 넘어간다.
            continue

    # 모든 모델 요청이 실패하면 마지막 오류 내용을 안내한다.
    return f"AI 응답 생성 중 오류가 발생했습니다: {str(last_error)}"


# 사용자의 고민 정보를 바탕으로 AI에게 전달할 프롬프트를 생성하는 함수
# categories: 선택한 고민 카테고리 목록
# style: 선택한 조언 스타일의 식별값
# title: 사용자가 입력한 고민 제목
# content: 사용자가 작성한 고민 내용
# conditions: 추가 조건 및 특별한 상황
# options: 추가 선택지 정보
def build_prompt(categories, style, title, content, conditions, options) -> str:
    """개선 1~5: 카테고리(복수), 스타일, 자유 제목, 가이드 기반 내용, 추가 조건을 반영한 프롬프트."""

    # 선택한 스타일에 해당하는 설명을 가져온다.
    # 존재하지 않는 스타일이면 objective를 기본값으로 사용한다.
    style_guide = STYLES.get(style, STYLES["objective"])

    # 선택한 카테고리들을 쉼표와 공백으로 연결한다.
    # 카테고리를 선택하지 않았다면 '지정 없음'을 사용한다.
    cat_text = ", ".join(categories) if categories else "지정 없음"

    # AI에게 전달할 내용을 문장 단위로 리스트에 저장한다.
    lines = [
        # AI가 수행해야 할 역할을 알려준다.
        "당신은 고민 해결을 돕는 상담 전문가입니다. 아래 상담 요청에 답해주세요.",

        # AI 응답의 길이를 간결하게 제한하도록 안내한다.
        "답변은 500자 안내로 간결하게 작성해주세요.",

        # 보기 좋게 구분하기 위한 빈 줄
        "",
        # 사용자가 선택한 고민 카테고리
        f"[고민 카테고리] {cat_text}",

        # AI가 따라야 하는 조언 스타일
        f"[조언 스타일] {style_guide}",

        # 고민 제목이 없으면 '제목 없음'으로 표시한다.
        f"[고민 제목] {title or '제목 없음'}",

        # 고민 내용을 구분하기 위한 빈 줄
        "",
        # 실제 사용자가 작성한 고민 내용의 시작
        "[고민 내용]",

        # 사용자가 입력한 고민 내용을 전달한다.
        content,

        # 추가 조건을 구분하기 위한 빈 줄
        "",
        # 사용자가 선택하거나 입력한 추가 조건
        # 조건이 비어 있다면 '없음'으로 표시한다.
        f"[추가 조건 및 특별한 상황] {conditions or '없음'}",

        # 요구사항을 구분하기 위한 빈 줄
        "",
        # 아래 항목들은 AI가 답변을 작성할 때 지켜야 할 규칙이다.
        "요구사항:",

        # 고민 상황을 먼저 짧게 정리하도록 한다.
        "1. 고민 내용을 바탕으로 상황을 짧게 정리해주세요.",

        # 선택지가 있다면 각각의 장단점을 비교하도록 한다.
        "2. 선택지가 있다면 선택지별 장단점을 현실적으로 비교해주세요.",

        # 사용자가 선택한 조언 스타일을 유지하도록 한다.
        "3. 지정된 조언 스타일의 말투와 태도를 유지해주세요.",

        # 미래를 확정적으로 예측하지 않고 판단에 필요한 정보를 제공하도록 한다.
        "4. 미래나 관계의 결과를 단정하지 말고, 판단 재료를 제시하는 방식으로 조언해주세요.",

        # 답변의 마지막에 추천 결론을 제시하도록 한다.
        "5. 마지막에 한 줄 추천 결론을 정리해주세요.",
    ]

    # 리스트에 담긴 모든 문장을 줄바꿈 문자로 연결해
    # AI에게 전달할 하나의 문자열로 만든다.
    return "\n".join(lines)
